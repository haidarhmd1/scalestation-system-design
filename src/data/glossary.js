// Terms marked `word: true` (short ones like TTL, NAT, MAC) only match whole
// words, so “settle” doesn't count as “ttl”. A plural “s” is allowed.
const esc = (m) => m.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const wordRe = {};
const hits = (g, id, t) => g.match.some((m) => {
  if (!g.word) return t.includes(m);
  const re = wordRe[`${id}|${m}`] ||= new RegExp(`(^|[^a-z0-9])${esc(m)}s?(?![a-z0-9])`);
  return re.test(t);
});

export function termsIn(text) {
  const t = text.toLowerCase();
  return GLOSSARY_ORDER.filter((id) => hits(GLOSSARY[id], id, t));
}
